export const LANGS = ['en', 'ja']

function initial() {
  try {
    const saved = localStorage.getItem('agent-calendar.lang')
    if (LANGS.includes(saved)) return saved
  } catch {
    // 覚えておけない環境ではブラウザの言語で決める
  }
  return (globalThis.navigator?.language ?? '').startsWith('ja') ? 'ja' : 'en'
}

export const lang = ref(initial())

export function setLang(l) {
  lang.value = l
  try {
    localStorage.setItem('agent-calendar.lang', l)
  } catch {
    // 保存できなくても表示は切り替わる
  }
}

// t('detail.prompts', { n: 3 })。見つからないキーはそのまま返す（抜けが画面で分かる）
export function t(key, params = {}) {
  const msg = key.split('.').reduce((o, k) => o?.[k], MESSAGES[lang.value])
  if (typeof msg !== 'string') return key
  return msg.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''))
}

// 日付・時刻の書式に使うロケール
export const locale = () => (lang.value === 'ja' ? 'ja-JP' : 'en-US')

